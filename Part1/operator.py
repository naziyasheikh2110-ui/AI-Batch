a = 10
b = 9

# Arithmetic operators - +, -, *, /, %

print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a % b)
print(a ** b) # a raised to the power of b a^b

# Relational operators  >, >=, <, <=, ==, !=

print( a > b )
print( a < b )
print( a == b )
print( a != b )

# Assignment Operators  =, +=, -=, *=, /=, %=

a+=4   # a =a + 4
print(a)
a-=b  # a = a - b
print(a)
a*=b  # a = a * b
print(a)
a/=b  # a = a / b
print(a)

# Logical Opearator - and, or , not

print(not(4>5))
print(4<5 and 5>3)
print(4>5 or 5<3)

# Operator precedence - PEMDAS (Parenthesis, Exponents, Multiplication, Division, Addition, Subtraction)
# if same precedence then it will be evaluated from left to right